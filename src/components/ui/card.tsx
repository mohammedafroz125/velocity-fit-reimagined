import * as React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { variant?: "default" | "warm" | "dark" | "elevated" }
>(({ className, variant = "default", ...props }, ref) => {
  const variantStyles = {
    default: "bg-paper/70 border-ink/10 text-ink shadow-subtle",
    warm: "bg-paper border-ink/10 text-ink shadow-subtle",
    dark: "bg-[#221F1C] border-ivory/10 text-ivory shadow-card",
    elevated: "bg-ivory border-ink/10 text-ink shadow-elevated",
  };

  return (
    <div
      ref={ref}
      className={cn(
        "rounded-2xl border transition-all duration-200",
        variantStyles[variant],
        className
      )}
      {...props}
    />
  );
});
Card.displayName = "Card";

